const assert=require('node:assert/strict');
const v=require('./web/visuals.js');
assert.equal(v.peakHeight(0),0);
assert.equal(v.peakHeight(null),0);
assert.equal(v.peakHeight(NaN),0);
assert.equal(v.peakHeight(1),100);
assert.ok(Math.abs(v.peakDb(.1)+20)<.0001);
assert.ok(v.peakHeight(.5)>v.peakHeight(.1));
assert.equal(v.positionAt({playing:true,position:10,duration:100},1000,1500),10.5);
assert.equal(v.positionAt({playing:true,position:10,duration:100},1000,10000),11.2);
assert.equal(v.positionAt({playing:false,position:10,duration:100},1000,1500),10);
assert.equal(v.positionAt({playing:true,position:99.8,duration:100},1000,1500),100);
assert.equal(v.timeLabel(144.545),'2:24');
assert.equal(v.theme({accent:'url(evil)'},'#8de4c7').accent,'#8de4c7');
assert.equal(v.mixerBackground({playerBackground:'artwork',mixerBackground:'match'}),'artwork');
assert.equal(v.mixerBackground({playerBackground:'colors',mixerBackground:'match'}),'colors');
assert.equal(v.mixerBackground({playerBackground:'off',mixerBackground:'match'}),'off');
assert.equal(v.mixerBackground({playerBackground:'artwork',mixerBackground:'off'}),'off');
assert.equal(v.mixerBackground({playerBackground:'off',mixerBackground:'artwork'}),'artwork');
console.log('Signal scaling, stale playback, pause, duration bounds and artwork fallback checks passed.');
